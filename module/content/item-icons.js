export function getCatalogItemIcon(localizationKey) {
  const [, group, key, , itemKey] = localizationKey.split('.');
  const icon = group === 'backstory' ? BACKSTORY_ICONS[key]?.[itemKey] : STANDARD_ICONS[group]?.[key];
  if (!icon || !ICONS[icon]) throw new Error(`Missing item icon for ${localizationKey}`);
  return ICONS[icon];
}
